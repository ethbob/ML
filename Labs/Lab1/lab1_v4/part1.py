def read_list():
    """Считывает список чисел через пробел. Пустой ввод: случайный список."""
    raw = input("Введите числа через пробел (Enter: случайный список): ").strip()
    if not raw:
        nums = [random.randint(-10, 50) for _ in range(10)]
        print("Сгенерирован список:", nums)
        return nums
    return [int(x) for x in raw.split()]


def task3():
    try:
        nums = read_list()
    except ValueError:
        print("Ошибка: вводите только целые числа")
        return
    if len(nums) < 3:
        print("Нужно хотя бы 3 элемента")
        return

    # а) Произведение элементов с нечётными номерами.
    # В Python нумерация (индексы) идёт с 0, поэтому нечётные номера это 1, 3, 5, ...
    # Срез nums[1::2]: начинаем с индекса 1 и берём каждый второй.
    odd = nums[1::2]
    product = 1
    for x in odd:
        product *= x
    print(f"Элементы с нечётными индексами: {odd}")
    print(f"Их произведение: {product}")

    # б) Наибольший элемент, удаляем его и выводим новый список.
    original = nums.copy()      # копия, чтобы исходный список остался для пункта в)
    biggest = max(nums)
    nums.remove(biggest)        # remove удаляет ПЕРВОЕ вхождение значения
    print(f"Наибольший элемент: {biggest}")
    print(f"Список после удаления: {nums}")

    # в) Три наибольших элемента исходного списка.
    # sorted(..., reverse=True) сортирует по убыванию, срез [:3] берёт первые три.
    top3 = sorted(original, reverse=True)[:3]
    print(f"Три наибольших элемента: {top3}")


