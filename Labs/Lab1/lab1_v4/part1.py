# Задание 2. Слова-палиндромы в строке (2 балла)
# ---------------------------------------------------------------------------
def task2():
    text = input("Введите строку текста: ")

    palindromes = []
    for word in text.split():                      # делим строку на слова по пробелам
        clean = word.strip(".,!?;:\"'()-«»…").lower()  # убираем знаки препинания и регистр
        # Палиндром читается одинаково в обе стороны.
        # clean[::-1] это срез с шагом -1, то есть строка задом наперёд.
        # Однобуквенные слова («а», «и») палиндромы тривиально, их не считаем.
        if len(clean) > 1 and clean == clean[::-1]:
            palindromes.append(clean)

    if palindromes:
        print("Слова-палиндромы:", ", ".join(palindromes))
    else:
        print("Палиндромов в строке нет")


