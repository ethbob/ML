# Задание 4. Словарь из двух списков (2 балла)
# ---------------------------------------------------------------------------
def task4():
    keys = input("Первый список (ключи) через пробел: ").split()
    values = input("Второй список (значения) через пробел: ").split()

    if len(keys) != len(values):
        print(f"Ошибка: длины списков разные ({len(keys)} и {len(values)})")
        return

    # Способ 1: вручную, по индексам.
    result = {}
    for i in range(len(keys)):
        result[keys[i]] = values[i]

    # Способ 2: zip склеивает списки в пары (ключ, значение), dict делает из пар словарь.
    result2 = dict(zip(keys, values))

    print("Словарь:", result)
    print("То же через dict(zip(...)):", result2)
    if len(result) < len(keys):
        print("Внимание: в первом списке были повторы, у словаря ключи уникальны,"
              " поэтому остались последние значения")


