# Задание 1. Сумма цифр натурального числа (1 балл)
# ---------------------------------------------------------------------------
def task1():
    text = input("Введите натуральное число: ").strip()

    # Натуральное число: только цифры и больше нуля.
    # str.isdigit() вернёт True, только если все символы строки цифры.
    if not text.isdigit() or int(text) == 0:
        print("Ошибка: нужно натуральное число (1, 2, 3, ...)")
        return

    # Способ 1: строка это последовательность символов, проходим по ней
    # и каждую цифру-символ превращаем в число.
    total = sum(int(ch) for ch in text)

    # Способ 2 (арифметический): % 10 даёт последнюю цифру, // 10 её отрезает.
    n, total2 = int(text), 0
    while n > 0:
        total2 += n % 10
        n //= 10

    print(f"Сумма цифр числа {text} = {total}")
    print(f"(проверка арифметическим способом: {total2})")


