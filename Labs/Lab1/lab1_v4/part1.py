# Задание 5. Программа «Ювелирный магазин» (2 балла)
# ---------------------------------------------------------------------------
# Ключ: название изделия. Значение: список [состав, цена за 1 шт (руб.), количество (шт)].
SHOP = {
    "кольцо":   ["золото 585", 450.0, 10],
    "серьги":   ["серебро 925, фианиты", 120.0, 15],
    "цепочка":  ["золото 750", 890.0, 5],
    "браслет":  ["серебро 925", 95.5, 8],
    "кулон":    ["платина, бриллиант", 1500.0, 3],
}
DESCRIPTION, PRICE, COUNT = 0, 1, 2   # индексы внутри списка-значения, чтобы код читался


def buy(shop):
    """Пункт «Покупка»: вводим название и количество, n: выход. Возвращает сумму."""
    total = 0.0
    cart = {}
    while True:
        name = input("Название изделия (n: закончить покупку): ").strip().lower()
        if name == "n":
            break
        if name not in shop:
            print("Такого изделия нет. В наличии:", ", ".join(shop))
            continue
        try:
            qty = int(input("Количество, шт: "))
        except ValueError:
            print("Количество должно быть целым числом")
            continue
        if qty <= 0:
            print("Количество должно быть больше нуля")
            continue
        if qty > shop[name][COUNT]:
            print(f"В наличии только {shop[name][COUNT]} шт")
            continue

        shop[name][COUNT] -= qty                    # уменьшаем остаток в магазине
        cost = qty * shop[name][PRICE]
        total += cost
        cart[name] = cart.get(name, 0) + qty        # get возвращает 0, если ключа ещё нет
        print(f"Добавлено: {name} x {qty} = {cost:.2f} руб.")

    if cart:
        print("\nВаша покупка:")
        for name, qty in cart.items():
            print(f"  {name}: {qty} шт")
        print(f"Итого к оплате: {total:.2f} руб.")
    print("\nОстаток товаров в магазине:")
    for name, info in shop.items():
        print(f"  {name}: {info[COUNT]} шт")
    return total


def task5():
    shop = {k: v.copy() for k, v in SHOP.items()}   # копия, чтобы исходный словарь не портился
    menu = ("\n=== Ювелирный магазин ===\n"
            "1. Просмотр описания\n2. Просмотр цены\n3. Просмотр количества\n"
            "4. Вся информация\n5. Покупка\n6. До свидания")
    while True:
        print(menu)
        choice = input("Ваш выбор: ").strip()
        if choice == "1":
            for name, info in shop.items():
                print(f"{name} – {info[DESCRIPTION]}")
        elif choice == "2":
            for name, info in shop.items():
                print(f"{name} – {info[PRICE]:.2f} руб.")
        elif choice == "3":
            for name, info in shop.items():
                print(f"{name} – {info[COUNT]} шт")
        elif choice == "4":
            for name, (desc, price, count) in shop.items():   # распаковка списка в три переменные
                print(f"{name}: состав – {desc}; цена – {price:.2f} руб.; в наличии – {count} шт")
        elif choice == "5":
            buy(shop)
        elif choice == "6":
            print("До свидания!")
            break
        else:
            print("Нет такого пункта, введите число от 1 до 6")


