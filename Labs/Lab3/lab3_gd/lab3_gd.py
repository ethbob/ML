# ## Теория коротко
#
# **Линейная регрессия** предсказывает число как взвешенную сумму признаков:
#
# $$\hat y = w_0 + w_1 x_1 + w_2 x_2 + \dots + w_m x_m = X w,$$
#
# где $w_0$ — свободный член (bias). Чтобы записать его в общую формулу, к матрице признаков слева добавляют столбец из единиц.
#
# **Функция потерь** — среднеквадратичная ошибка (MSE): насколько в среднем предсказания промахиваются:
#
# $$Q(w) = \frac{1}{n}\sum_{i=1}^{n}(x_i w - y_i)^2 = \frac{1}{n}\|Xw - y\|^2.$$
#
# **Градиент** — вектор частных производных $Q$ по каждому весу. Он показывает направление, в котором ошибка **растёт быстрее всего**:
#
# $$\nabla Q(w) = \frac{2}{n} X^T (Xw - y).$$
#
# **Градиентный спуск**: шагаем в сторону, **противоположную** градиенту (вниз по «склону» ошибки), на величину шага $\eta$ — скорость обучения:
#
# $$w^k = w^{k-1} - \eta\, \nabla Q(w^{k-1}).$$
#
# Повторяем, пока веса перестанут заметно меняться: $\|w^k - w^{k-1}\| < \varepsilon$.
#
# | | Градиентный спуск (GD) | Стохастический (SGD) |
# |---|---|---|
# | градиент считается по | **всем** n объектам | **одному** случайному объекту |
# | цена одной итерации | O(n·m) | O(m) |
# | траектория | гладкая | «шумная», скачет |


