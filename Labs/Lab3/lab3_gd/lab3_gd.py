# ## 6. L1-регуляризация (вариант 4 — чётный)
#
# **Зачем.** Регуляризация штрафует модель за большие веса, чтобы она не переобучалась и не опиралась на бесполезные признаки.
# L1-регуляризация (**Lasso**) добавляет к ошибке сумму модулей весов:
#
# $$Q_{L1}(w) = \frac{1}{n}\|Xw - y\|^2 + \lambda \sum_{j=1}^{m} |w_j|.$$
#
# - $\lambda$ — коэффициент регуляризации: чем он больше, тем сильнее веса прижимаются к нулю;
# - свободный член $w_0$ **не штрафуем**: он отвечает за общий сдвиг, а не за влияние признаков.
#
# **Главное свойство L1:** веса не просто уменьшаются, а становятся **ровно нулём**. Модель сама отбирает признаки:
# сначала обнуляются бесполезные (у нас x4, x5), при большом $\lambda$ — все.
# (L2-регуляризация, для нечётных вариантов, штрафует $\lambda\sum w_j^2$ и только уменьшает веса, не обнуляя.)
#
# **Как это реализовать в градиентном спуске.** Производная $|w|$ — это $\text{sign}(w)$, но в нуле она не определена,
# и при простом шаге $w - \eta\lambda\,\text{sign}(w)$ вес «прыгает» вокруг нуля, никогда не становясь нулём.
# Поэтому шаг делаем в два этапа (метод **ISTA**, проксимальный градиентный спуск):
# 1. обычный шаг по градиенту MSE: $z = w - \eta \nabla \text{MSE}$;
# 2. «мягкий порог» (soft thresholding): каждый вес приближаем к нулю на $\eta\lambda$, а если он был меньше этой величины — ставим ровно 0:
#
# $$w_j = \text{sign}(z_j)\cdot\max(|z_j| - \eta\lambda,\ 0).$$

def soft_threshold(z, t):
    # приблизить каждое значение к нулю на t; то, что ближе к нулю, чем t, — обнулить
    return np.sign(z) * np.maximum(np.abs(z) - t, 0.0)


def gradient_descent_l1(X_b, y, lam, lr=0.1, eps=1e-8, max_iter=20_000):
    n, m = X_b.shape
    w = np.zeros(m)                                        # 1) начальные веса
    for k in range(1, max_iter + 1):                       # 2) цикл
        grad = 2 / n * X_b.T @ (X_b @ w - y)               #    градиент MSE
        z = w - lr * grad                                  # 3a) обычный шаг
        w_new = z.copy()
        w_new[1:] = soft_threshold(z[1:], lr * lam)        # 3b) L1: мягкий порог (кроме bias)
        if np.linalg.norm(w_new - w) < eps:                # 4) стоп
            return w_new, k
        w = w_new
    return w, max_iter


# Проверим на одном значении $\lambda$, что реализация верная: сравним со `sklearn.linear_model.Lasso`.
# У sklearn функция потерь записана как $\frac{1}{2n}\|Xw-y\|^2 + \alpha\|w\|_1$ — это наша формула, делённая на 2,
# поэтому нашему $\lambda$ соответствует $\alpha = \lambda / 2$.

lam = 10
w_l1, it = gradient_descent_l1(X_b, y, lam=lam)
sk = Lasso(alpha=lam / 2).fit(X_scaled, y)
