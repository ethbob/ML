# ## 4. Стохастический градиентный спуск
#
# Добавляем в функцию параметр `stochastic`. Если он включён, на каждой итерации градиент считается **по одному случайному объекту**:
#
# $$\nabla Q_i(w) = 2\, x_i^T (x_i w - y_i).$$
#
# Это в n раз дешевле, но градиент «шумный»: один объект плохо представляет всю выборку.
# Поэтому:
# - шаг постепенно уменьшаем: $\eta_k = \eta_0 / (1 + k \cdot decay)$ — в формуле из задания это и есть $\eta_k$, зависящий от итерации;
# - правило остановки по $\|w^k - w^{k-1}\|$ для SGD ненадёжно (случайно маленький шаг ещё не значит, что дошли до минимума),
#   поэтому SGD останавливается по числу итераций или когда шаг станет совсем маленьким.

def gradient_descent(X_b, y, lr=0.1, eps=1e-6, max_iter=10_000,
                     stochastic=False, decay=0.0, random_state=None):
    rng = np.random.default_rng(random_state)
    n, m = X_b.shape
    w = np.zeros(m)                                   # 1) начальные веса
    history = [mse(X_b, y, w)]
    for k in range(1, max_iter + 1):                  # 2) цикл по итерациям
        if stochastic:
            i = rng.integers(n)                       #    случайный объект
            xi, yi = X_b[i], y[i]
            grad = 2 * xi * (xi @ w - yi)             #    градиент по ОДНОМУ объекту
        else:
            grad = 2 / n * X_b.T @ (X_b @ w - y)      #    градиент по ВСЕМ объектам
        eta = lr / (1 + decay * k)                    #    шаг η_k (при decay=0 постоянный)
        w_new = w - eta * grad                        # 3) новые веса
        history.append(mse(X_b, y, w_new))
        if not np.isfinite(history[-1]) or history[-1] > 1e12:  # спуск «улетел»
            return w_new, history, k
        if np.linalg.norm(w_new - w) < eps:           # 4) условие остановки
            return w_new, history, k
        w = w_new
    return w, history, max_iter


