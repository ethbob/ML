# ## 2. Функция градиентного спуска
#
# Пишем строго по алгоритму из задания:
# 1. инициализируем веса нулями и задаём ε;
# 2. цикл по количеству итераций;
# 3. новые веса: $w^k = w^{k-1} - \eta \nabla Q$;
# 4. выходим, если $\|w^k - w^{k-1}\| < \varepsilon$.
#
# Функция возвращает итоговые веса, **историю MSE** по итерациям (для графиков) и номер итерации, на которой остановились.

def gradient_descent(X_b, y, lr=0.1, eps=1e-6, max_iter=10_000):
    n, m = X_b.shape
    w = np.zeros(m)                          # 1) начальные веса
    history = [mse(X_b, y, w)]
    for k in range(1, max_iter + 1):         # 2) цикл по итерациям
        grad = 2 / n * X_b.T @ (X_b @ w - y) #    градиент MSE по ВСЕМ объектам
        w_new = w - lr * grad                # 3) новые веса
        history.append(mse(X_b, y, w_new))
        if not np.isfinite(history[-1]) or history[-1] > 1e12:  # спуск «улетел» (слишком большой шаг)
            return w_new, history, k
        if np.linalg.norm(w_new - w) < eps:  # 4) веса почти не меняются — стоп
            return w_new, history, k
        w = w_new
    return w, history, max_iter

w_gd, hist_gd, it_gd = gradient_descent(X_b, y, lr=0.1)

print(f"Остановились на итерации {it_gd}, MSE = {hist_gd[-1]:.3f}")
